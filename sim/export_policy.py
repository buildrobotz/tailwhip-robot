"""Export the trained policy to a C header for the ESP32 ('onboard' mode) and check it matches.

    python sim/export_policy.py                       # sim/policies/tailwhip.zip -> firmware/tailwhip_robot/policy.h

The network is obs(52) -> 64 tanh -> 64 tanh -> 3 linear, clipped to [-1, 1]: the PPO actor mean. The header
also carries the observation mean and std (identity here: the observation is already scaled by hand).
"""
import argparse, os
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def weights(path):
    from stable_baselines3 import PPO
    p = PPO.load(path, device='cpu').policy
    lin = [m for m in p.mlp_extractor.policy_net if m.__class__.__name__ == 'Linear'] + [p.action_net]
    return [(l.weight.detach().numpy().astype(np.float32), l.bias.detach().numpy().astype(np.float32)) for l in lin], p


def forward(Ws, x):
    h = x
    for i, (Wm, b) in enumerate(Ws):
        h = Wm @ h + b
        if i < len(Ws) - 1:
            h = np.tanh(h)
    return np.clip(h, -1, 1)


def arr(name, a):
    flat = ', '.join(f'{v:.8e}f' for v in a.ravel())   # always a float literal ("0f" is not C++)
    shape = ''.join(f'[{s}]' for s in a.shape)
    return f'static const float {name}{shape} = {{{flat}}};\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--policy', default=os.path.join(HERE, 'policies', 'tailwhip.zip'))
    ap.add_argument('--out', default=os.path.join(ROOT, 'firmware', 'tailwhip_robot', 'policy.h'))
    args = ap.parse_args()
    Ws, pol = weights(args.policy)
    assert [w.shape for w, _ in Ws] == [(64, 52), (64, 64), (3, 64)], [w.shape for w, _ in Ws]
    # check against the torch policy on random inputs
    import torch
    rng = np.random.default_rng(0)
    worst = 0.0
    for _ in range(200):
        x = rng.normal(0, 0.5, 52).astype(np.float32)
        with torch.no_grad():
            ref = pol.get_distribution(torch.as_tensor(x[None])).distribution.mean.numpy()[0]
        worst = max(worst, float(np.abs(np.clip(ref, -1, 1) - forward(Ws, x)).max()))
    h = ['// Generated by sim/export_policy.py from ' + os.path.relpath(args.policy, ROOT) + '. Do not edit.\n',
         '// obs(52) -> 64 tanh -> 64 tanh -> 3, output clipped to [-1, 1]. See docs/software.md.\n',
         '#pragma once\n#define TW_OBS_DIM 52\n#define TW_HID 64\n#define TW_ACT_DIM 3\n',
         arr('TW_W0', Ws[0][0]), arr('TW_B0', Ws[0][1]), arr('TW_W1', Ws[1][0]), arr('TW_B1', Ws[1][1]),
         arr('TW_W2', Ws[2][0]), arr('TW_B2', Ws[2][1]),
         arr('TW_OBS_MEAN', np.zeros(52, np.float32)), arr('TW_OBS_STD', np.ones(52, np.float32))]
    with open(args.out, 'w') as f:
        f.write(''.join(h))
    n = sum(w.size + b.size for w, b in Ws)
    print(f'wrote {args.out}: {n} parameters ({n * 4 / 1024:.1f} KB of flash), max |numpy - torch| = {worst:.2e}')


if __name__ == '__main__':
    main()
